-- Filet : un réservoir trop maigre est un incident de vente, pas un détail d'exploitation.
do $$
declare
  libres integer;
begin
  select count(*) into libres from public.identity
  where profession = 'commercial' and status = 'free';

  if libres < 300 then
    raise exception 'Réservoir insuffisant : % identités libres pour le métier commercial (300 attendues).', libres;
  end if;
end;
$$;
