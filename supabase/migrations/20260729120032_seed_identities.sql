-- FOND-34 — le réservoir d'identités du métier Commercial.
-- Réalise : FOND-34
--
-- « Les identités sont choisies automatiquement par Sentio. Le client ne choisit jamais. Une
-- identité ne peut jamais être réutilisée. Chaque employé est unique » (projet.md §9).
--
-- L'unicité est GLOBALE, pas par entreprise : deux clients ne doivent jamais avoir un employé
-- portant le même nom. La contrainte `unique (first_name, last_name)` la garantit, et
-- `reserve_identity()` la consomme de façon atomique.
--
-- Le réservoir doit être garni AVANT la première vente : un recrutement qui échoue faute
-- d'identité disponible est un paiement encaissé sans employé livré. D'où plusieurs centaines
-- d'entrées dès le départ (docs/03-modele-de-donnees.md).
--
-- Le portrait reste nul : il suppose un hébergement d'images et un droit d'usage, ni l'un ni
-- l'autre tranchés, et aucun des deux n'est nécessaire pour recruter. À traiter au lot 6, quand
-- la fiche employé existera.
--
-- `on conflict do nothing` : rejouer ne duplique rien et ne libère jamais une identité déjà
-- prise — une identité libérée n'est jamais remise en circulation.

